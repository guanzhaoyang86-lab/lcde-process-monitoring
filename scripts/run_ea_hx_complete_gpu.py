"""Run EA-HX-CUSUM development, ablation, and fresh-seed confirmation."""

from __future__ import annotations

import torch  # noqa: F401  # Windows torch-first DLL loading contract

from datetime import datetime, timezone
import json
from pathlib import Path
import time
from typing import Any

import numpy as np

from mate_spc_cris_v9.baselines import PredictiveResidualCUSUMBaseline
from mate_spc_cris_v9.energy_anchor_monitor import EnergyAnchoredHXMonitor
from mate_spc_cris_v9.model import CRISModel
from mate_spc_cris_v9.monitor import (
    PointCalibrator,
    calibrate_trajectory_threshold,
    scan_innovations,
)
from mate_spc_cris_v9.simulator import CRISBatch, simulate_batch
from mate_spc_cris_v9.study import (
    FAULT_KINDS,
    candidate_specs,
    evaluate_baselines,
    innovation_runs,
    load_study_charter,
    sha256_file,
    simulate_role,
    summarize_paths,
)


PROJECT = Path(__file__).resolve().parents[1]
CHARTER_PATH = PROJECT / "protocols" / "cris_v9_four_tank_study_charter.json"
MODEL_PATH = PROJECT / "outputs" / "cris_v9_four_tank" / "cris_v9_model.npz"
OUTPUT_ROOT = PROJECT / "outputs" / "ea_hx_cusum"
CACHE_ROOT = OUTPUT_ROOT / "innovation_cache"
DEVELOPMENT_RESULT = OUTPUT_ROOT / "development_and_ablation.json"
FINAL_RESULT = OUTPUT_ROOT / "fresh_confirmation_all_methods.json"

DEVELOPMENT_ROLES = (
    "development_healthy",
    "development_sensor_bias",
    "development_intermittent_pump",
    "development_valve_stiction",
    "development_dependence_shift",
    "development_covariate_shift_only",
)

# These deterministic seeds are disjoint from every existing charter role and
# had not been generated by an earlier experiment.
FRESH_CONFIRMATION = (
    ("fresh_healthy", "healthy", 1_000_001),
    ("fresh_sensor_bias", "sensor_bias", 1_010_001),
    ("fresh_intermittent_pump", "intermittent_pump", 1_020_001),
    ("fresh_valve_stiction", "valve_stiction", 1_030_001),
    ("fresh_dependence_shift", "dependence_shift", 1_040_001),
    ("fresh_covariate_shift_only", "covariate_shift_only", 1_050_001),
)
RUNS_PER_CONDITION = 200


def _progress(label: str):
    def report(done: int, total: int) -> None:
        if done == 1 or done % 50 == 0 or done == total:
            print(f"[innovations] {label}: {done}/{total}", flush=True)

    return report


def _write(path: Path, document: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        json.dumps(document, indent=2, sort_keys=True, ensure_ascii=True) + "\n",
        encoding="ascii",
        newline="\n",
    )
    temporary.replace(path)


def _cached_innovations(
    label: str,
    model: CRISModel,
    batch: CRISBatch,
    charter: dict[str, Any],
    model_hash: str,
) -> tuple[np.ndarray, ...]:
    CACHE_ROOT.mkdir(parents=True, exist_ok=True)
    path = CACHE_ROOT / f"{label}.npz"
    if path.exists():
        with np.load(path, allow_pickle=False) as archive:
            if set(archive.files) != {"innovations", "seeds", "model_sha256"}:
                raise ValueError(f"invalid innovation cache schema: {path}")
            values = np.array(archive["innovations"], copy=True)
            seeds = np.array(archive["seeds"], copy=True)
            stored_hash = str(np.asarray(archive["model_sha256"]).item())
        if stored_hash != model_hash or not np.array_equal(seeds, batch.seed):
            raise ValueError(f"innovation cache identity mismatch: {path}")
        print(f"[cache-hit] {label}", flush=True)
        return tuple(np.array(run, copy=True) for run in values)

    runs = innovation_runs(
        model,
        batch,
        charter,
        device="cuda",
        progress=_progress(label),
    )
    temporary = path.with_suffix(".tmp.npz")
    np.savez_compressed(
        temporary,
        innovations=np.stack(runs),
        seeds=batch.seed,
        model_sha256=np.asarray(model_hash),
    )
    temporary.replace(path)
    return runs


def _scorecard(summaries: dict[str, dict[str, Any]]) -> dict[str, Any]:
    recalls = [float(summaries[kind]["recall"]) for kind in FAULT_KINDS]
    delays = [
        float(summaries[kind]["median_relative_delay"]) for kind in FAULT_KINDS
    ]
    healthy = float(summaries["healthy"]["alarm_rate"])
    covariate = float(summaries["covariate_shift_only"]["alarm_rate"])
    return {
        "macro_fault_recall": float(np.mean(recalls)),
        "minimum_fault_recall": min(recalls),
        "worst_median_relative_delay": max(delays),
        "mean_median_relative_delay": float(np.mean(delays)),
        "healthy_alarm_rate": healthy,
        "covariate_shift_alarm_rate": covariate,
        "maximum_negative_control_alarm_rate": max(healthy, covariate),
        "both_negative_controls_at_or_below_0_10": (
            healthy <= 0.10 and covariate <= 0.10
        ),
    }


def _monitor_record(
    monitor: Any,
    threshold: Any,
    evaluation: dict[str, tuple[CRISBatch, tuple[np.ndarray, ...]]],
    charter: dict[str, Any],
    *,
    family: str,
) -> dict[str, Any]:
    summaries: dict[str, dict[str, Any]] = {}
    for _role, (batch, runs) in evaluation.items():
        paths = tuple(monitor.score(run).path for run in runs)
        summaries[batch.fault_kind[0]] = summarize_paths(
            paths, batch, threshold.threshold, charter
        )
    return {
        "method": monitor.name,
        "family": family,
        "threshold": {
            "value": threshold.threshold,
            "alpha": threshold.alpha,
            "ascending_rank": threshold.rank,
            "calibration_run_count": int(threshold.calibration_maxima.size),
        },
        "summaries": summaries,
        "scorecard": _scorecard(summaries),
    }


def _fit_ablation_monitors(
    reference: tuple[np.ndarray, ...],
) -> tuple[Any, ...]:
    return (
        PredictiveResidualCUSUMBaseline.fit(reference),
        EnergyAnchoredHXMonitor.fit(
            reference, include_horizon=True, include_cross_channel=False
        ),
        EnergyAnchoredHXMonitor.fit(
            reference, include_horizon=False, include_cross_channel=True
        ),
        EnergyAnchoredHXMonitor.fit(
            reference, include_horizon=True, include_cross_channel=True
        ),
    )


def _balanced_key(item: dict[str, Any]) -> tuple[Any, ...]:
    score = item["scorecard"]
    return (
        -score["minimum_fault_recall"],
        -score["macro_fault_recall"],
        score["worst_median_relative_delay"],
        score["maximum_negative_control_alarm_rate"],
    )


def _strict_key(item: dict[str, Any]) -> tuple[Any, ...]:
    score = item["scorecard"]
    return (not score["both_negative_controls_at_or_below_0_10"],) + _balanced_key(item)


def _fresh_batch(kind: str, first_seed: int) -> CRISBatch:
    seeds = tuple(range(first_seed, first_seed + RUNS_PER_CONDITION))
    return simulate_batch((kind,) * RUNS_PER_CONDITION, seeds)


def main() -> int:
    started = time.perf_counter()
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    if FINAL_RESULT.exists():
        raise FileExistsError(f"final result already exists: {FINAL_RESULT}")

    charter = load_study_charter(CHARTER_PATH)
    model = CRISModel.load_npz(MODEL_PATH)
    model_hash = sha256_file(MODEL_PATH)
    print(f"[gpu] {model.attestation.cuda_device_name}", flush=True)

    fit_batch = simulate_role(charter, "healthy_model_fit")
    reference_batch = simulate_role(charter, "healthy_point_reference")
    reference = _cached_innovations(
        "healthy_point_reference", model, reference_batch, charter, model_hash
    )
    threshold_batch = simulate_role(charter, "healthy_threshold_calibration")
    calibration = _cached_innovations(
        "healthy_threshold_calibration", model, threshold_batch, charter, model_hash
    )

    monitors = _fit_ablation_monitors(reference)
    alpha = float(charter["method"]["trajectory_alpha"])
    thresholds = tuple(
        monitor.calibrate_trajectory_threshold(calibration, alpha=alpha)
        for monitor in monitors
    )

    development: dict[str, tuple[CRISBatch, tuple[np.ndarray, ...]]] = {}
    for role in DEVELOPMENT_ROLES:
        print(f"[development] {role}", flush=True)
        batch = simulate_role(charter, role)
        runs = _cached_innovations(role, model, batch, charter, model_hash)
        development[role] = (batch, runs)

    development_methods = [
        _monitor_record(
            monitor, threshold, development, charter, family="ea_hx_ablation"
        )
        for monitor, threshold in zip(monitors, thresholds, strict=True)
    ]
    anchor = development_methods[0]["scorecard"]
    proposed = development_methods[-1]["scorecard"]
    development_document = {
        "schema": "ea_hx_cusum_development_and_ablation",
        "created_utc": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "device": model.attestation.cuda_device_name,
        "model_sha256": model_hash,
        "method_frozen_before_fresh_confirmation": {
            "id": "ea_hx_cusum",
            "energy_anchor": "predictive_residual_cusum",
            "structure_targets": ["level_1", "level_2", "level_3", "level_4"],
            "horizon_product_count": 12,
            "cross_channel_product_count": 18,
            "fusion": "S_E + 0.25 * min(S_E, S_HX)",
        },
        "methods": development_methods,
        "full_minus_anchor": {
            "macro_fault_recall": (
                proposed["macro_fault_recall"] - anchor["macro_fault_recall"]
            ),
            "minimum_fault_recall": (
                proposed["minimum_fault_recall"] - anchor["minimum_fault_recall"]
            ),
            "worst_median_relative_delay": (
                proposed["worst_median_relative_delay"]
                - anchor["worst_median_relative_delay"]
            ),
            "maximum_negative_control_alarm_rate": (
                proposed["maximum_negative_control_alarm_rate"]
                - anchor["maximum_negative_control_alarm_rate"]
            ),
        },
    }
    _write(DEVELOPMENT_RESULT, development_document)
    print(f"[checkpoint] {DEVELOPMENT_RESULT}", flush=True)

    # Only now generate the fresh, disjoint test block.  The full EA-HX method
    # and all ablation settings above are fixed and are not selected from it.
    fresh: dict[str, tuple[CRISBatch, tuple[np.ndarray, ...]]] = {}
    fresh_seed_document: dict[str, dict[str, Any]] = {}
    for role, kind, first_seed in FRESH_CONFIRMATION:
        print(f"[fresh-confirmation] {role}", flush=True)
        batch = _fresh_batch(kind, first_seed)
        runs = _cached_innovations(role, model, batch, charter, model_hash)
        fresh[role] = (batch, runs)
        fresh_seed_document[role] = {
            "condition": kind,
            "first": first_seed,
            "last": first_seed + RUNS_PER_CONDITION - 1,
            "count": RUNS_PER_CONDITION,
        }

    methods = [
        _monitor_record(monitor, threshold, fresh, charter, family="ea_hx_ablation")
        for monitor, threshold in zip(monitors, thresholds, strict=True)
    ]

    print("[comparison] CRIS candidates", flush=True)
    for spec in candidate_specs(charter):
        calibrator = PointCalibrator.fit(reference, spec.monitor_config)
        calibration_paths = tuple(
            scan_innovations(run, calibrator).score for run in calibration
        )
        threshold = calibrate_trajectory_threshold(calibration_paths, alpha=alpha)
        summaries: dict[str, dict[str, Any]] = {}
        for _role, (batch, runs) in fresh.items():
            paths = tuple(scan_innovations(run, calibrator).score for run in runs)
            summaries[batch.fault_kind[0]] = summarize_paths(
                paths, batch, threshold, charter
            )
        methods.append(
            {
                "method": spec.candidate_id,
                "family": "cris_hmm_scan",
                "threshold": {
                    "value": threshold.value,
                    "alpha": threshold.alpha,
                    "ascending_rank": threshold.ascending_rank,
                    "calibration_run_count": threshold.calibration_run_count,
                },
                "summaries": summaries,
                "scorecard": _scorecard(summaries),
            }
        )

    print("[comparison] PCA and observation-energy baselines", flush=True)
    baseline_results = evaluate_baselines(
        fit_batch,
        reference,
        threshold_batch,
        calibration,
        fresh,
        charter,
    )
    existing_names = {item["method"] for item in methods}
    for result in baseline_results:
        if result.baseline.name in existing_names:
            continue
        summaries = {name: dict(value) for name, value in result.summaries.items()}
        methods.append(
            {
                "method": result.baseline.name,
                "family": "frozen_baseline",
                "threshold": {
                    "value": result.threshold.threshold,
                    "alpha": result.threshold.alpha,
                    "ascending_rank": result.threshold.rank,
                    "calibration_run_count": int(
                        result.threshold.calibration_maxima.size
                    ),
                },
                "summaries": summaries,
                "scorecard": _scorecard(summaries),
            }
        )

    proposed_monitor = monitors[-1]
    first_run = next(iter(fresh.values()))[1][0]
    components = proposed_monitor.score_components(first_run)
    anchor_path = monitors[0].score(first_run).path
    np.testing.assert_array_equal(components.energy_path, anchor_path)
    np.testing.assert_array_equal(
        proposed_monitor.score(first_run).path,
        proposed_monitor.score(first_run).path,
    )

    method_by_name = {item["method"]: item for item in methods}
    base_score = method_by_name["predictive_residual_cusum"]["scorecard"]
    full_score = method_by_name["ea_hx_cusum"]["scorecard"]
    document = {
        "schema": "ea_hx_cusum_fresh_confirmation_all_methods",
        "created_utc": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "elapsed_seconds": time.perf_counter() - started,
        "device": {
            "source_device": model.source_device,
            "cuda_device_name": model.attestation.cuda_device_name,
            "torch_version": model.attestation.torch_version,
            "cuda_runtime": model.attestation.cuda_runtime,
        },
        "charter_sha256": sha256_file(CHARTER_PATH),
        "model_sha256": model_hash,
        "fresh_seed_roles": fresh_seed_document,
        "methods": methods,
        "balanced_ranking": [
            item["method"] for item in sorted(methods, key=_balanced_key)
        ],
        "strict_gate_first_ranking": [
            item["method"] for item in sorted(methods, key=_strict_key)
        ],
        "ea_hx_minus_predictive_anchor": {
            name: full_score[name] - base_score[name]
            for name in (
                "macro_fault_recall",
                "minimum_fault_recall",
                "worst_median_relative_delay",
                "mean_median_relative_delay",
                "healthy_alarm_rate",
                "covariate_shift_alarm_rate",
            )
        },
        "verification": {
            "energy_anchor_exactly_matches_predictive_residual_cusum": True,
            "repeat_score_exact": True,
            "fresh_confirmation_generated_after_method_freeze": True,
        },
    }
    _write(FINAL_RESULT, document)
    print(f"[result] {FINAL_RESULT}", flush=True)
    print(f"[balanced-ranking] {document['balanced_ranking']}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
